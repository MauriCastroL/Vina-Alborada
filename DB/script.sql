            RAISE_APPLICATION_ERROR(-20202, 'CLIENTE NATURAL SOLO REQUIERE NOMBRE Y 2 APELLIDOS, SIN RAZON SOCIAL');
        END IF;

    ELSIF :NEW.TIPO_CLIENTE = 'EMPRESA' THEN

