CREATE OR REPLACE FUNCTION CEMJ_F_PK_CATEGORIA
RETURN CEMJ_CATEGORIA_PRODUCTO.ID_CATEGORIA%TYPE
IS
    V_ID CEMJ_CATEGORIA_PRODUCTO.ID_CATEGORIA%TYPE;
BEGIN
    SELECT NVL(MAX(ID_CATEGORIA)+1, 1)
    INTO V_ID
    FROM CEMJ_CATEGORIA_PRODUCTO;

    RETURN V_ID;
END;
/

CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_CATEGORIA_ID
FOR INSERT ON CEMJ_CATEGORIA_PRODUCTO
COMPOUND TRIGGER

    V_SIGUIENTE CEMJ_CATEGORIA_PRODUCTO.ID_CATEGORIA%TYPE;

    BEFORE STATEMENT IS
    BEGIN
        V_SIGUIENTE := CEMJ_FN_PK_CATEGORIA;
    END BEFORE STATEMENT;

    BEFORE EACH ROW IS
    BEGIN
        IF :NEW.ID_CATEGORIA IS NULL THEN
            :NEW.ID_CATEGORIA := V_SIGUIENTE;
            V_SIGUIENTE := V_SIGUIENTE + 1;

        ELSIF :NEW.ID_CATEGORIA >= V_SIGUIENTE THEN
            V_SIGUIENTE := :NEW.ID_CATEGORIA + 1;
        END IF;
    END BEFORE EACH ROW;

END CEMJ_TRIGGER_CATEGORIA_ID;
/

CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_CATEGORIA_MAYUS
BEFORE INSERT OR UPDATE
ON CEMJ_CATEGORIA_PRODUCTO
