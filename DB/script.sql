-- ===================== MOVIMIENTO_INVENTARIO =========================
CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_MOVIMINETO_INVENTARIO_INSERT
BEFORE INSERT
ON CEMJ_MOVIMIENTO_INVENTARIO
FOR EACH ROW
BEGIN
    IF :NEW.ESTADO IS NULL THEN
        :NEW.ESTADO := 'BORRADOR';
    END IF;

    IF :NEW.FECHA_CREACION IS NULL THEN
        :NEW.FECHA_CREACION := SYSDATE;
    END IF;

    IF :NEW.NUMERO_FOLIO IS NULL THEN
        :NEW.NUMERO_FOLIO := CEMJ_SEQ_FOLIO_MOVIMIENTO.NEXTVAL;
    END IF;

    IF :NEW.TIPO_MOVIMIENTO IS NULL OR :NEW.TIPO_MOVIMIENTO NOT IN (
            'ENTRADA', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO',
            'SALIDA_VENTA', 'REVERSION_VENTA'
       ) THEN
        RAISE_APPLICATION_ERROR(-20225, 'TIPO DE MOVIMIENTO NO VALIDO');
    END IF;

    IF :NEW.CANTIDAD IS NULL OR :NEW.CANTIDAD <= 0 THEN
        RAISE_APPLICATION_ERROR(-20226, 'LA CANTIDAD DEBE SER MAYOR A 0');
    END IF;

    IF :NEW.ESTADO NOT IN ('BORRADOR', 'APLICADO', 'ANULADO') THEN
        RAISE_APPLICATION_ERROR(-20227, 'EL ESTADO DE MOVIMIENTO NO ES VALIDO');
    END IF;

    IF :NEW.ESTADO IN ('BORRADOR','ANULADO') THEN
        IF :NEW.FECHA_APLICACION IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20228, 'MOVIMIENTO BORRADOR O ANULADO NO DEBE TENER FECHA DE APLICACION');
        END IF;
    ELSIF :NEW.ESTADO = 'APLICADO' THEN
        IF :NEW.FECHA_APLICACION IS NULL THEN
            RAISE_APPLICATION_ERROR(-20228, 'MOVIMIENTO APLICADO REQUIERE FECHA DE APLICACION');
        END IF;
    END IF;

    IF :NEW.FECHA_APLICACION IS NOT NULL AND :NEW.FECHA_APLICACION < :NEW.FECHA_CREACION THEN
        RAISE_APPLICATION_ERROR(-20229, 'LA FECHA DE APLICACION NO PUEDE SER ANTERIOR A LA CREACION');
    END IF;

    IF :NEW.TIPO_MOVIMIENTO IN ('ENTRADA', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO') THEN
        IF :NEW.ID_VENTA IS NOT NULL OR :NEW.ID_MOVIMIENTO_ORIGEN IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20230, 'ESTE TIPO DE MOVIMIENTO NO DEBE TENER VENTA NI UN MOVIMIENTO DE ORIGEN');
        END IF;

    ELSIF :NEW.TIPO_MOVIMIENTO = 'SALIDA_VENTA' THEN
        IF :NEW.ID_VENTA IS NULL OR :NEW.ID_MOVIMIENTO_ORIGEN IS NOT NULL OR :NEW.ESTADO != 'APLICADO' THEN
            RAISE_APPLICATION_ERROR(-20230, 'SALIDA DE VENTA REQUIERE VENTA, SIN ORIGEN Y EN ESTADO APLICADO');
        END IF;

    ELSIF :NEW.TIPO_MOVIMIENTO = 'REVERSION_VENTA' THEN

        IF :NEW.ID_VENTA IS NULL OR :NEW.ID_MOVIMIENTO_ORIGEN IS NULL OR :NEW.ESTADO != 'APLICADO' THEN
            RAISE_APPLICATION_ERROR(-20230, 'REVERSION REQUIERE VENTA, MOVIMIENTO ORIGEN Y ESTADO APLICADO');
        END IF;

    END IF;

    IF :NEW.TIPO_MOVIMIENTO IN ('AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO') AND TRIM(:NEW.MOTIVO) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20231, 'LOS AJUSTES REQUIEREN UN MOTIVO');
    END IF;
