BEFORE UPDATE
ON CEMJ_SOLICITUD_COMPRA
FOR EACH ROW
BEGIN
    IF :NEW.ESTADO IS NULL OR :NEW.ESTADO NOT IN ('BORRADOR', 'PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CANCELADA', 'ANULADA') THEN
        RAISE_APPLICATION_ERROR(-20211, 'ESTADO DE SOLICITUD NO VALIDO');
    END IF;

    -- LA ANULACION UNICAMENTE PUEDE VENIR DESDE EL BORRADOR
    IF :NEW.ESTADO = 'ANULADA' AND :OLD.ESTADO <> 'BORRADOR' THEN
        RAISE_APPLICATION_ERROR(-20214, 'SOLO UNA SOLICITUD EN BORRADOR PUEDE SER ANULADA');
    END IF;

    IF NOT (
        (:NEW.ESTADO IN ('BORRADOR','ANULADA') AND :NEW.FECHA_ENVIO IS NULL
         AND :NEW.ID_USUARIO_CIERRE IS NULL AND :NEW.FECHA_CIERRE IS NULL)
        OR
        (:NEW.ESTADO = 'PENDIENTE' AND :NEW.FECHA_ENVIO IS NOT NULL
         AND :NEW.ID_USUARIO_CIERRE IS NULL AND :NEW.FECHA_CIERRE IS NULL)
        OR
        (:NEW.ESTADO IN ('ACEPTADA','RECHAZADA','CANCELADA') AND :NEW.FECHA_ENVIO IS NOT NULL
         AND :NEW.ID_USUARIO_CIERRE IS NOT NULL AND :NEW.FECHA_CIERRE IS NOT NULL)
    ) THEN
        RAISE_APPLICATION_ERROR(-20212, 'FECHAS O USUARIO DE CIERRE NO CORRESPONDEN AL ESTADO DE LA SOLICITUD');
    END IF;

    IF :NEW.FECHA_ENVIO IS NOT NULL AND :NEW.FECHA_ENVIO < :NEW.FECHA_CREACION THEN
        RAISE_APPLICATION_ERROR(-20213, 'FECHA DE ENVIO NO PUEDE SER ANTERIOR A FECHA DE CREACION');
    END IF;

    IF :NEW.FECHA_CIERRE IS NOT NULL AND :NEW.FECHA_ENVIO IS NOT NULL AND :NEW.FECHA_CIERRE < :NEW.FECHA_ENVIO THEN
        RAISE_APPLICATION_ERROR(-20213, 'LA FECHA DE CIERRE NO PUEDE SER ANTERIOR A FECHA DE ENVIO');
    END IF;
END;

