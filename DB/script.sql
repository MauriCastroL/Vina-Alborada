CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_AUDITORIA_INSERT
BEFORE INSERT
ON CEMJ_AUDITORIA
FOR EACH ROW
BEGIN
    IF :NEW.FECHA IS NULL THEN
        :NEW.FECHA := SYSDATE;
    END IF;

    IF :NEW.USUARIO_BD IS NULL THEN
        :NEW.USUARIO_BD := USER;
    END IF;

    IF :NEW.USUARIO_APP IS NULL THEN
        :NEW.USUARIO_APP := SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER');
    END IF;

    IF :NEW.EQUIPO IS NULL THEN
        :NEW.EQUIPO := SYS_CONTEXT('USERENV', 'HOST');
    END IF;

    IF :NEW.NOMBRE_TABLA IS NULL OR :NEW.OPERACION IS NULL THEN
        RAISE_APPLICATION_ERROR(-20237, 'NOMBRE DE TABLA Y OPERACION SON OBLIGATORIOS');
    ELSIF :NEW.NOMBRE_TABLA = 'LOGIN' THEN
        IF :NEW.OPERACION NOT IN ('LOGIN_OK', 'LOGIN_FALLIDO') THEN
            RAISE_APPLICATION_ERROR(-20237, 'OPERACION DE AUDITORIA LOGIN NO VALIDA');
        END IF;
    ELSIF :NEW.NOMBRE_TABLA = 'INVENTARIO' THEN
        IF :NEW.OPERACION NOT IN ('ALERTA_STOCK', 'STOCK_REPUESTO') THEN
            RAISE_APPLICATION_ERROR(-20237, 'OPERACION DE AUDITORIA INVENTARIO NO VALIDA');
        END IF;
    ELSE
        IF :NEW.OPERACION NOT IN ('INSERT', 'UPDATE', 'DELETE') THEN
            RAISE_APPLICATION_ERROR(-20237, 'OPERACION DE AUDITORIA NO VALIDA');
        END IF;

    END IF;
END;

