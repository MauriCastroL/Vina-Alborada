-- ============================= VENTA =================================
CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_VENTA_INSERT
BEFORE INSERT
ON CEMJ_VENTA
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_CREACION IS NULL THEN
        :NEW.FECHA_CREACION := SYSDATE;
    END IF;

    IF :NEW.ESTADO IS NULL THEN
        :NEW.ESTADO := 'BORRADOR';
    END IF;

    IF :NEW.ID_SOLICITUD IS NULL THEN
        :NEW.CANAL_VENTA := 'PRESENCIAL';
    ELSE
        :NEW.CANAL_VENTA := 'DIGITAL';
    END IF;

    IF :NEW.ID_SOLICITUD IS NULL THEN
        IF TRIM(:NEW.LUGAR_VENTA) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20216, 'VENTA PRESENCIAL REQUIERE LUGAR DE VENTA');
        END IF;
    ELSE
        IF :NEW.ID_CLIENTE IS NOT NULL OR :NEW.NOMBRE_COMPRADOR IS NOT NULL OR :NEW.LUGAR_VENTA IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20216, 'UNA VENTA DIGITAL NO LLEVA CLIENTE, COMPRADOR NI LUGAR');
        END IF;
    END IF;

    IF :NEW.ID_CLIENTE IS NOT NULL AND :NEW.NOMBRE_COMPRADOR IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20217, 'INDICAR CLIENTE O NOMBRE DE COMPRADOR, NO AMBOS');
    END IF;

    IF :NEW.ESTADO NOT IN ('BORRADOR', 'CONFIRMADA', 'ANULADA') THEN
        RAISE_APPLICATION_ERROR(-20218, 'ESTADO DE VENTA NO VALIDO');
    END IF;

    IF :NEW.ESTADO = 'BORRADOR' THEN
        IF :NEW.FECHA_CONFIRMACION IS NOT NULL OR :NEW.FECHA_ANULACION IS NOT NULL OR :NEW.ID_USUARIO_ANULA IS NOT NULL OR :NEW.MOTIVO_ANULACION IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20219, 'LOS DATOS NO CORRESPONDEN A UNA VENTA EN BORRADOR');
        END IF;

    ELSIF :NEW.ESTADO = 'CONFIRMADA' THEN
        IF :NEW.FECHA_CONFIRMACION IS NULL OR :NEW.FECHA_ANULACION IS NOT NULL
           OR :NEW.ID_USUARIO_ANULA IS NOT NULL OR :NEW.MOTIVO_ANULACION IS NOT NULL THEN
            RAISE_APPLICATION_ERROR(-20219, 'LOS DATOS NO CORRESPONDEN A UNA VENTA CONFIRMADA');
        END IF;

    ELSIF :NEW.ESTADO = 'ANULADA' THEN
        IF :NEW.FECHA_CONFIRMACION IS NULL OR :NEW.FECHA_ANULACION IS NULL
           OR :NEW.ID_USUARIO_ANULA IS NULL OR TRIM(:NEW.MOTIVO_ANULACION) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20219, 'LOS DATOS DE ANULACION ESTAN INCOMPLETOS');
        END IF;
    END IF;

    IF :NEW.FECHA_CONFIRMACION IS NOT NULL AND :NEW.FECHA_CONFIRMACION < :NEW.FECHA_CREACION THEN
        RAISE_APPLICATION_ERROR(-20220, 'FECHA CONFIRMACION NO PUEDE SER ANTERIOR A CREACION');
    END IF;

    IF :NEW.FECHA_ANULACION IS NOT NULL AND :NEW.FECHA_CONFIRMACION IS NOT NULL AND :NEW.FECHA_ANULACION < :NEW.FECHA_CONFIRMACION THEN
        RAISE_APPLICATION_ERROR(-20220, 'FECHA ANULACION NO PUEDE SER ANTERIOR A CONFIRMACION');
    END IF;
END;

