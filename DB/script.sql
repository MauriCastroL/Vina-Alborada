CREATE OR REPLACE FUNCTION CEMJ_FN_PRODUCTO_COMPOSICION(
    P_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE
)
RETURN VARCHAR2
IS
    CURSOR C_CEPAS(C_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE) IS
        SELECT C.NOMBRE, PC.PORCENTAJE
        FROM CEMJ_PRODUCTO_CEPA PC
        JOIN CEMJ_CEPA C ON C.ID_CEPA = PC.ID_CEPA
        WHERE PC.ID_PRODUCTO = C_ID_PRODUCTO
        ORDER BY PC.PORCENTAJE DESC, C.NOMBRE;

    V_COMPOSICION VARCHAR2(1000);
BEGIN
    V_COMPOSICION := NULL;

    FOR R_CEPA IN C_CEPAS(P_ID_PRODUCTO) LOOP
        IF V_COMPOSICION IS NULL THEN
            V_COMPOSICION := CONCAT(
                CONCAT(R_CEPA.NOMBRE, ' '),
                CONCAT(TO_CHAR(R_CEPA.PORCENTAJE), '%')
            );
        ELSE
            V_COMPOSICION := CONCAT(
                CONCAT(V_COMPOSICION, ', '),
                CONCAT(
                    CONCAT(R_CEPA.NOMBRE, ' '),
                    CONCAT(TO_CHAR(R_CEPA.PORCENTAJE), '%')
                )
            );
        END IF;
    END LOOP;

    RETURN V_COMPOSICION;
END;
