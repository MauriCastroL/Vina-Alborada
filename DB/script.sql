-- ======================== SOLICITUD_COMPRA ===========================
CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_SOLICITUD_INSERT
BEFORE INSERT
ON CEMJ_SOLICITUD_COMPRA
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_CREACION IS NULL THEN
        :NEW.FECHA_CREACION := SYSDATE;
    END IF;

    IF :NEW.ESTADO IS NULL THEN
        :NEW.ESTADO := 'BORRADOR';
    END IF;

    IF :NEW.NUMERO_FOLIO IS NULL THEN
        :NEW.NUMERO_FOLIO := CEMJ_SEQ_FOLIO_SOLICITUD.NEXTVAL;
    END IF;

    IF :NEW.ESTADO NOT IN ('BORRADOR', 'PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CANCELADA', 'ANULADA') THEN
        RAISE_APPLICATION_ERROR(-20211, 'ESTADO DE SOLICITUD NO VALIDO');
    END IF;

    -- VALIDAMOS LOS CAMPOS SEGUN SU ESTADO
    IF NOT ((:NEW.ESTADO IN ('BORRADOR','ANULADA') AND :NEW.FECHA_ENVIO IS NULL 
        AND :NEW.ID_USUARIO_CIERRE IS NULL AND :NEW.FECHA_CIERRE IS NULL)
        OR
        (:NEW.ESTADO = 'PENDIENTE' AND :NEW.FECHA_ENVIO IS NOT NULL 
        AND :NEW.ID_USUARIO_CIERRE IS NULL AND :NEW.FECHA_CIERRE IS NULL)
        OR
        (:NEW.ESTADO IN ('ACEPTADA','RECHAZADA','CANCELADA') AND :NEW.FECHA_ENVIO IS NOT NULL
        AND :NEW.ID_USUARIO_CIERRE IS NOT NULL AND :NEW.FECHA_CIERRE IS NOT NULL)
    ) THEN

        RAISE_APPLICATION_ERROR(-20212, 'FECHAS O USUARIO DE CIERRE NO CORRESPONDEN AL ESTADO DE LA SOLICITUD');
