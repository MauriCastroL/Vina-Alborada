        END IF;

        FOR R_CEPA IN C_COMPOSICION(P_ID_PRODUCTO) LOOP
            IF R_CEPA.ACTIVO = 0 THEN
                RAISE_APPLICATION_ERROR(-20121, 'EL PRODUCTO TIENE CEPAS ELIMINADAS: ' || R_CEPA.NOMBRE);
            END IF;
        END LOOP;

    END IF;

    UPDATE CEMJ_PRODUCTO SET
        ID_CATEGORIA = P_ID_CATEGORIA, CODIGO = UPPER(P_CODIGO), NOMBRE = P_NOMBRE,
        DESCRIPCION = P_DESCRIPCION, FORMATO = P_FORMATO, ANADA = P_ANADA,
        PRECIO_ACTUAL = P_PRECIO_ACTUAL, ACTIVO = P_ACTIVO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO;

