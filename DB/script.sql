CREATE OR REPLACE PROCEDURE CEMJ_PA_CATEGORIA_CREAR(
    P_NOMBRE CEMJ_CATEGORIA_PRODUCTO.NOMBRE%TYPE,
    P_DESCRIPCION CEMJ_CATEGORIA_PRODUCTO.DESCRIPCION%TYPE,
    P_UNIDAD_MEDIDA CEMJ_CATEGORIA_PRODUCTO.UNIDAD_MEDIDA%TYPE
)
IS
BEGIN
    LOCK TABLE CEMJ_CATEGORIA_PRODUCTO IN EXCLUSIVE MODE;

    INSERT INTO CEMJ_CATEGORIA_PRODUCTO(NOMBRE, DESCRIPCION, UNIDAD_MEDIDA)
    VALUES(UPPER(P_NOMBRE), P_DESCRIPCION, UPPER(P_UNIDAD_MEDIDA));
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE FUNCTION CEMJ_FN_CATEGORIA_UNIDAD(
    P_ID_CATEGORIA CEMJ_CATEGORIA_PRODUCTO.ID_CATEGORIA%TYPE
)
RETURN CEMJ_CATEGORIA_PRODUCTO.UNIDAD_MEDIDA%TYPE
IS
    V_UNIDAD CEMJ_CATEGORIA_PRODUCTO.UNIDAD_MEDIDA%TYPE;
BEGIN
    SELECT UNIDAD_MEDIDA INTO V_UNIDAD
    FROM CEMJ_CATEGORIA_PRODUCTO
    WHERE ID_CATEGORIA = P_ID_CATEGORIA;

    RETURN V_UNIDAD;
END;
/

CREATE OR REPLACE FUNCTION CEMJ_FN_CATEGORIA_CANT_PROD(
    P_ID_CATEGORIA CEMJ_CATEGORIA_PRODUCTO.ID_CATEGORIA%TYPE
)
RETURN NUMBER
IS
    V_CANTIDAD NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_CANTIDAD
    FROM CEMJ_PRODUCTO
    WHERE ID_CATEGORIA = P_ID_CATEGORIA;

    RETURN V_CANTIDAD;
END;
