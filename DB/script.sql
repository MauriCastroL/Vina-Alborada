CREATE OR REPLACE FUNCTION CEMJ_FN_AUD_CAMBIO(
    P_CAMPO VARCHAR2, P_ANTES VARCHAR2, P_DESPUES VARCHAR2
)
RETURN VARCHAR2
IS
BEGIN
    IF (P_ANTES IS NULL AND P_DESPUES IS NULL) OR P_ANTES = P_DESPUES THEN
        RETURN NULL;
    END IF;

    RETURN CONCAT(
        CONCAT(
            CONCAT(
                CONCAT(
                    CONCAT(P_CAMPO, ': '),
                    NVL(P_ANTES, '(vacio)')
                ),
                ' -> '
            ),
            NVL(P_DESPUES, '(vacio)')
        ),
        '; '
    );
END;
