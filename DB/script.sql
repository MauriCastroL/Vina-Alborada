-- ============================ CLIENTE ================================
CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_CLIENTE_INSERT
BEFORE INSERT
ON CEMJ_CLIENTE
FOR EACH ROW
BEGIN
    IF :NEW.FECHA_REGISTRO IS NULL THEN
        :NEW.FECHA_REGISTRO := SYSDATE;
    END IF;

    IF :NEW.ACTIVO IS NULL THEN
        :NEW.ACTIVO := 1;
    END IF;


    IF :NEW.ACTIVO NOT IN (0,1) THEN
        RAISE_APPLICATION_ERROR(-20232, 'ACTIVO DE LA TABLA CLIENTE DEBE SER 0 O 1');
    END IF;

    IF :NEW.TIPO_CLIENTE IS NULL OR :NEW.TIPO_CLIENTE NOT IN ('NATURAL','EMPRESA') THEN
        RAISE_APPLICATION_ERROR(-20201, 'EL TIPO DE CLIENTE DEBE SER NATURAL O EMPRESA');
    END IF;

    IF :NEW.TIPO_CLIENTE = 'NATURAL' THEN

        IF TRIM(:NEW.NOMBRE) IS NULL
           OR TRIM(:NEW.APELLIDO1) IS NULL
           OR TRIM(:NEW.APELLIDO2) IS NULL
           OR :NEW.RAZON_SOCIAL IS NOT NULL THEN

            RAISE_APPLICATION_ERROR(-20202, 'UN CLIENTE NATURAL REQUIERE NOMBRE Y 2 APELLIDOS, SIN RAZON SOCIAL');
        END IF;

    ELSIF :NEW.TIPO_CLIENTE = 'EMPRESA' THEN

        IF TRIM(:NEW.RUT) IS NULL
           OR TRIM(:NEW.RAZON_SOCIAL) IS NULL
           OR :NEW.NOMBRE IS NOT NULL
           OR :NEW.APELLIDO1 IS NOT NULL
           OR :NEW.APELLIDO2 IS NOT NULL THEN

            RAISE_APPLICATION_ERROR(-20203, 'UN CLIENTE DE TIPO EMPRESA REQUIERE RUT Y RAZON SOCIAL, SIN NOMBRE NI APELLIDOS');
        END IF;

    END IF;
END;
/
